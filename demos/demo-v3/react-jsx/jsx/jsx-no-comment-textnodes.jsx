
// ==========================================================
// react/jsx-no-comment-textnodes 示例
// ----------------------------------------------------------
// 规则含义：JSX 的文本节点中不能直接出现 `// ...` 或 `/* ... */`
// 这样的 JS 注释写法。JSX 文本节点里的这些字符会被当作**纯文本**
// 渲染出来，容易造成 bug；正确做法是使用 `{/* ... */}` 或 `{"// ..."}`。
//
// 推荐配置：["error"]（无 options）
// ==========================================================

 
/* eslint-disable import/no-unresolved */
/* eslint-disable react/function-component-definition */
/* eslint-disable react/jsx-curly-brace-presence */

import React from "react";

function Demo() {
  return (
    <div>
      {/* ---------------- ✅ 正确示例 ---------------- */}
      {/* 正确：使用 JSX 表达式包裹的注释 */}
      <span>hello</span>
      {/* 正确：如果确实要展示 "// xxx" 这种字符串，用字符串表达式 */}
      <span>{"// 这是一段被当作字符串展示的伪注释"}</span>

      {/* ---------------- ❌ 错误示例 ---------------- */}
      {/* 错误：直接把双斜杠注释写在文本节点里，会被当成文本渲染 */}
      <span>// 这里其实会被渲染成文本，而不是注释</span>
      {/* 错误：块注释形式的文本同样会被当作文本渲染，而不是注释 */}
      <span>/* 这段同样会被渲染成文本 */</span>
    </div>
  );
}

export default Demo;
